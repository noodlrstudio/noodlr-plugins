// Reads the props of every @noodlr/ui Play node control and writes them to
// src/generated/ui-catalogue.ts, so the MCP server's component reference
// stays in step with the UI kit.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sourceDir = resolve(here, "../../ui/src/play-node");
const output = resolve(here, "../src/generated/ui-catalogue.ts");

const index = await readFile(resolve(sourceDir, "index.ts"), "utf8");
const exportNames = new Map(
  [
    ...index.matchAll(
      /export \{ default as (\w+) \} from "\.\/(\w+)\.svelte"/g,
    ),
  ].map(([, name, file]) => [file, name]),
);

const components = [];
for (const file of (await readdir(sourceDir)).sort()) {
  if (!file.endsWith(".svelte")) continue;
  const source = await readFile(resolve(sourceDir, file), "utf8");
  const script = source.match(/<script[^>]*>([\s\S]*?)<\/script>/)?.[1] ?? "";
  const props = [];
  const lines = script.split("\n");
  for (let i = 0; i < lines.length; i += 1) {
    if (!/^\s*export let /.test(lines[i])) continue;
    let declaration = lines[i].trim();
    // Join multi-line declarations up to the closing semicolon.
    while (!declaration.endsWith(";") && i + 1 < lines.length) {
      i += 1;
      declaration += " " + lines[i].trim();
    }
    props.push(
      declaration
        .replace(/^export let /, "")
        .replace(/;$/, "")
        .replace(/\s+/g, " "),
    );
  }
  const fileName = basename(file, ".svelte");
  components.push({
    name: exportNames.get(fileName) ?? fileName,
    file,
    props,
  });
}

const body = `// Generated by scripts/generate-ui-catalogue.mjs. Do not edit.
export interface UiComponentEntry {
  name: string;
  file: string;
  props: readonly string[];
}

export const UI_COMPONENTS: readonly UiComponentEntry[] = ${JSON.stringify(components, null, 2)};
`;
await writeFile(output, body);
console.log(`Wrote ${components.length} components to ${output}`);
